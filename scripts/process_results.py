def get_k_codes(execs:List, r:int, selection_strategy:str, k:int, data_row:int) -> List[Dict]:
    """
    Retrieves k best codes from a list of execution results by applying post-generation selection heuristics.

    Args:
        execs (List): A list of execution entries generated by scripts.run_codes_on_tests. Must include all cross-evaluations of codes and test suites up to and including round r.
        r (int): The round up to which codes and test suites should be considered.
        selection_strategy (str): The post-generation selection heuristic. Must be one of
            - `max_pass_hard`: corresponds to MaxPass Hard in the paper
            - `max_pass_soft`: corresponds to MaxPass Soft in the paper
            - `mbr_hard`: corresponds to MBR-Exec Hard in the paper
            - `mbr_soft`: corresponds to MBR-Exec Soft in the paper
            - `codet_hard`: corresponds to CodeT Hard in the paper
            - `codet_soft`: corresponds to CodeT Soft in the paper
            - `last`: corresponds to Last Selection or Random Selection in the paper (last selection for in-context Thompson sampling, random for independent generation without backprompting)
            - `random`: corresponds to Random Selection in the paper (random for independent generation and random for in-context Thompson sampling)
        k: How many to return. -1 returns all
        data_row (int): The row of the dataset considered, used to mark rows when a missing entries error is thrown

    Returns:
        The k codes that score the highest on the post-generation selection.
    """
    items = [item for item in execs if item['r_code'] >= 0 and item['r_code'] <= r and item['r_tests'] >= 0 and item['r_tests'] <= r] # simulates iteration
    codes = []
    for r_code in range(r+1):
        code = list({item['code'] for item in items if item['r_code'] == r_code})
        evaluations = [item['evaluation'] for item in items if item['r_code'] == r_code]
        assert len(code) == 1 and len(evaluations) == r+1, f"entries are missing for data row {data_row}" # ensures no entries are missing, e.g., due to a runtime error
        codes.append({'code': code[0], 'r_code': r_code, 'evals': evaluations})
    if r > 0: # selection only happens starting in the second round.
        if selection_strategy == 'last':
            codes = [code | {'score': code['r_code']} for code in codes]
        elif selection_strategy == 'random':
            codes = [code | {'score': random.random()} for code in codes]
        elif selection_strategy in ['max_pass_hard', 'max_pass_soft', 'mbr_hard', 'mbr_soft', 'codet_hard', 'codet_soft', 'b4']:
            # compute score (ranking) 
            codes = [code | {'expected_reward': sum([eval['score'] for eval in code['evals']])/(r+1)} for code in codes]
            codes = [code | {'expected_correct': sum([eval['score']==1 for eval in code['evals']])/(r+1)} for code in codes]
            codes = [code | {'status': list(itertools.chain.from_iterable(eval['status'] for eval in code['evals']))} for code in codes] # concatenates status lists (to identify code equivalence)
            codes = [code | {'expected_num_equal': (sum(all(s==t for s,t in zip(c['status'], code['status'])) for c in codes)-1)/r} for code in codes]
            codes = [code | {'expected_ratio_equal': (sum(sum(s==t for s,t in zip(c['status'], code['status']))/len(code['status']) for c in codes)-1)/r} for code in codes]
            if selection_strategy == 'max_pass_hard': # expected correct, i.e., E_h [1_{R(x,h)=1}]
                codes = [code | {'score': code['expected_correct']} for code in codes]
            if selection_strategy == 'max_pass_soft': # expected reward, i.e., E_h [R(x,h)]
                codes = [code | {'score': code['expected_reward']} for code in codes]
            if selection_strategy == 'mbr_hard': # minimum bayes risk, i.e., E_x' [1_(R(x,h) == R(x',h))]
                codes = [code | {'score': code['expected_num_equal']} for code in codes]
            elif selection_strategy == 'mbr_soft': # minimum bayes risk, i.e., E_x' [||R(x,h) == R(x',h)||_1 / dim(R(x',h))]
                codes = [code | {'score': code['expected_ratio_equal']} for code in codes]
            elif selection_strategy == 'codet_hard':
                codes = [code | {'score': code['expected_num_equal'] * code['expected_reward']} for code in codes]
            elif selection_strategy == 'codet_soft':
                codes = [code | {'score': code['expected_ratio_equal'] * code['expected_reward']} for code in codes]
            elif selection_strategy == 'b4': # B4: Towards optimal assessment of plausible code solutions with plausible tests
                N = len(codes)
                M = len(codes[0]['status']) # concatenated tests status of all test suites
                # Hyperparameters for real-world optimal B^4(4,3) variant (see Table 1 of the paper)
                beta_0 = 10000.0 # prior hyperparameter of theta_0 (prob that incorrect code passes incorrect test)
                alpha_xy = 1000.0 # prior hyperparameter for consensus set size
                
                def log_beta(a, b):
                    return math.lgamma(a) + math.lgamma(b) - math.lgamma(a + b)
                
                # defining consensus sets (corresponds to N_c^infty in our formalism)
                unique_y_hats = list(set(tuple(c['status']) for c in codes))
                scores_per_code = [-float('inf')] * N
                
                for y_hat in unique_y_hats:
                    x_hat = [1 if tuple(c['status']) == y_hat else 0 for c in codes] # binary list for which codes match test signature y_hat
                    
                    n_x = sum(x_hat) # how many codes match signature y_hat
                    n_y = sum(y_hat) # how many tests are passing for signature y_hat
                    
                    # likelihood computation
                    E_1_count = 0 # total number of cells mapping presumably incorrect codes to presumably correct tests
                    E_0_count = 0 # total number of cells mapping presumably incorrect codes to presumably incorrect tests
                    n_1 = 0 # how many times did a presumably incorrect test pass a presumably correct test
                    n_0 = 0 # how many times did a presumably incorrect test fail a presumably incorrect test
                    for i in range(N):
                        if x_hat[i] == 0: # code i does not match signature y_hat
                            for j in range(M):
                                if y_hat[j] == 1: # test j is presumably correct
                                    E_1_count += 1
                                    n_1 += codes[i]['status'][j]
                                else:
                                    E_0_count += 1
                                    n_0 += codes[i]['status'][j]
                                    
                    score = ( # maximum a posteriori of code
                        log_beta(n_1 + 1, E_1_count - n_1 + 1) + # likelihood
                        log_beta(n_0 + 1, E_0_count - n_0 + beta_0) + # likelihood
                        log_beta(n_x + alpha_xy, N - n_x + 1) + # prior
                        log_beta(n_y + alpha_xy, M - n_y + 1) # prior
                    )
                    
                    # assigns MAP to each code
                    for i in range(N):
                        if x_hat[i] == 1:
                            scores_per_code[i] = score
                            
                codes = [code | {'score': scores_per_code[i]} for i, code in enumerate(codes)]
        else:
            raise NotImplementedError
        #codes = sorted(codes, key=lambda c: c['r_code'], reverse=True) # first sort such that later generations are put first.
        codes = sorted(codes, key=lambda c: c['score'], reverse=True) # stable sort, i.e., earlier generations are put first (and thus are more likely to be extracted)
    if k != -1: # -1 is treated as pass@k
        codes = codes[:k]
    return codes

def get_token_counts(codes:List, tests:List, r:int) -> Tuple[int, int]:
    """
    Retrieves the total prompt and completion tokens spent during code and test suite generation by summing across rounds. 
    Make sure to divide the result by two if the code and test file coincide (such as when using scripts.in_context_thompson_sampling)

    Args:
        codes (List): a list of code entries
        tests (List): a list of test entries

    Returns:
        The prompt tokens and the completion tokens, each summed across the rounds and summed between code and test suite generation.
    """
    prompt_tokens = sum(code['token_counts']['prompt_tokens'] for code in codes[:r+1]) + sum(test['token_counts']['prompt_tokens'] for test in tests[:r+1])
    completion_tokens = sum(code['token_counts']['completion_tokens'] for code in codes[:r+1]) + sum(test['token_counts']['completion_tokens'] for test in tests[:r+1])
    return prompt_tokens, completion_tokens

def estimate_irreducible_regret(execs: List[Dict], window_rounds: List[int]) -> Dict:
    """
    Estimates the irreducible regret Delta for a single dataset entry.

    Based on Corollary 1 of the paper, two families of estimators are computed
    from the same moving window of model-generated codes and test suites:

    (A) Collision-probability estimator:
        1 - Delta = E_{c*_obs,1, c*_obs,2}[ sim(c*_obs,1, c*_obs,2) ]
      - soft (sim^1): average fraction of test-case outcomes that agree between two codes.
      - hard (sim^inf): 1 iff avg_frac_same across all test suites == 1, else 0.

    (B) Pass rate estimator:
        1 - Delta = E_{c*_obs}[ E_{t_true}[ 1_{R(c*_obs, t_true | e) = 1} ] ]
      - soft: for each c_n, average fraction of test cases passed across all t_{nt} in window.
      - hard: for each c_n, average indicator that ALL tests in t_{nt} pass, averaged across all t_{nt}.
      Both expectations are taken over the same window of model-generated test suites.

    Both codes and test suites are taken from the same moving window of the last
    `window_size` rounds, which approximates convergence of the Thompson sampling policy.

    Args:
        execs (List[Dict]): Execution entries from an execute_thompson_sampling_* directory.
            Each entry has 'r_code' (int), 'r_tests' (int), and 'evaluation' with 'status'
            (list of booleans, one per test case).
        window_rounds (List[int]): Round indices forming the convergence window,
            e.g., [7, 8, 9] for window_size=3 at round T=9.

    Returns:
        Dict with keys:
            'delta_sim_soft'  (float | None): 1 - collision_soft. None if fewer than 2 codes.
            'delta_sim_hard'  (float | None): 1 - collision_hard. None if fewer than 2 codes.
            'delta_pass_soft' (float): 1 - pass_rate_soft (pass rate estimator, soft variant).
            'delta_pass_hard' (float): 1 - pass_rate_hard (pass rate estimator, hard variant).
            'n_pairs'         (int): number of ordered off-diagonal code pairs used.
            'n_test_suites'   (int): number of distinct test suites in the window.
    """
    if len(window_rounds) < 2:
        return {'delta_sim_soft': None, 'delta_sim_hard': None, 'delta_pass_soft': None, 'delta_pass_hard': None, 'n_pairs': 0, 'n_test_suites': 0}

    # Build lookup table mapping (r_code, r_tests) to status list (booleans per test case).
    # Only consider entries where both r_code and r_tests are within the window
    window_set = set(window_rounds)
    status_map: Dict[Tuple[int, int], List] = {}
    for entry in execs:
        rc = entry['r_code']
        rt = entry['r_tests']
        if rc in window_set and rt in window_set:
            status_map[(rc, rt)] = entry['evaluation']['status']

    similarities_soft: List[float] = []
    similarities_hard: List[float] = []
    pass_rates_soft: List[float] = []
    pass_rates_hard: List[float] = []

    # Iterate over all ordered off-diagonal pairs of codes (n1 != n2 such that Monte Carlo estimation is unbiased)
    for n1 in window_rounds: # code 1
        for n2 in window_rounds: # code 2
            if n1 == n2:
                continue  # exclude self-pairs for an unbiased collision estimator

            # For each shared test suite t_{nt} from the window, compare c_{n1} vs c_{n2}
            frac_same_per_t: List[float] = []
            # Iterate over all test suites t_{nt} in the window to estimate similarity sim(c_{n1}, c_{n2})
            for nt in window_rounds:
                assert (n1, nt) in status_map, f"Missing cross-evaluation entry for (r_code={n1}, r_tests={nt})"
                assert (n2, nt) in status_map, f"Missing cross-evaluation entry for (r_code={n2}, r_tests={nt})"
                s1 = status_map[(n1, nt)]
                s2 = status_map[(n2, nt)]
                assert len(s1) == len(s2), f"Test suite length mismatch for r_tests={nt}: len(s1)={len(s1)} for r_code={n1} vs len(s2)={len(s2)} for r_code={n2}"
                num_tests = len(s1)
                assert num_tests > 0, f"Empty test status list for cross-evaluation between r_code={n1}/{n2} and r_tests={nt}"
                matches = sum(a == b for a, b in zip(s1, s2))
                frac_same_per_t.append(matches / num_tests)

            assert len(frac_same_per_t) == len(window_rounds), f"Expected {len(window_rounds)} test suite evaluations for code pair ({n1}, {n2})"
            avg_frac_same = sum(frac_same_per_t) / len(frac_same_per_t)
            similarities_soft.append(avg_frac_same)
            similarities_hard.append(1.0 if avg_frac_same == 1.0 else 0.0)

    # Pass rate estimator: 1 - Delta = E_{c*_obs}[ E_{t_true}[ 1_{R(c*_obs, t_true | e) = 1} ] ]
    # For each code c_n in the window, average its pass rate across all test suites t_{nt} in the window
    for n in window_rounds: # code
        frac_passed_per_t: List[float] = []
        all_passed_per_t: List[float] = []
        for nt in window_rounds:
            s = status_map[(n, nt)]  # already asserted to exist above
            num_tests = len(s)
            n_passed = sum(s)
            frac_passed_per_t.append(n_passed / num_tests)
            all_passed_per_t.append(1.0 if n_passed == num_tests else 0.0)
        pass_rates_soft.append(sum(frac_passed_per_t) / len(frac_passed_per_t))
        pass_rates_hard.append(sum(all_passed_per_t) / len(all_passed_per_t))

    n_pairs = len(similarities_soft)
    n_test_suites = len(window_rounds)

    # Collision probability = average pairwise similarity = 1 - Delta
    collision_soft = sum(similarities_soft) / n_pairs
    collision_hard = sum(similarities_hard) / n_pairs
    # Pass rate = average individual pass rate across codes and test suites
    pass_rate_soft = sum(pass_rates_soft) / len(pass_rates_soft)
    pass_rate_hard = sum(pass_rates_hard) / len(pass_rates_hard)

    return {
        'delta_sim_soft': 1.0 - collision_soft,
        'delta_sim_hard': 1.0 - collision_hard,
        'delta_pass_soft': 1.0 - pass_rate_soft,
        'delta_pass_hard': 1.0 - pass_rate_hard,
        'n_pairs': n_pairs,
        'n_test_suites': n_test_suites,
    }

if __name__ == '__main__':
    env = load_env(add_args=[
            {'name': '--k', 'type': int, 'default': 1, 'help': 'the k of pass@k, i.e., how many candidate solutions are checked against the ground-truth. -1 indicates proper pass@k, i.e., no subselection. Defaults to 1.'},
            {'name': '--selection_strategy', 'type': str, 'help': "the post-generation selection strategy. One of 'max_pass_hard', 'max_pass_soft', 'mbr_hard', 'mbr_soft', 'codet_hard', 'codet_soft', 'last', 'random', 'b4'."},
            {'name': '--use_surrogate_ground_truth', 'action': 'store_true', 'help': 'if set to true, returns the Pass@k on the surrogate test generated at each round by the LLM.'},
            {'name': '--estimate_delta', 'action': 'store_true', 'help': 'if set, estimates the irreducible regret Delta (hard and soft) at each round and adds it to the output.'},
            {'name': '--estimate_delta_window_size', 'type': int, 'default': 3, 'help': 'number of last rounds used as the convergence window for Delta estimation. Only relevant when --estimate_delta is set. Defaults to 3.'},
            ], requires_model=False)
    dataset = env['dataset']
    config = env['config']
    config_key = env['config_key']
    args = env['args']
    k = args.k
    selection_strategy = args.selection_strategy
    use_surrogate_ground_truth = args.use_surrogate_ground_truth
    estimate_delta = args.estimate_delta
    estimate_delta_window_size = args.estimate_delta_window_size
    result_dir = env['result_dir']
    code_dir = os.path.join(config['result_dir'], f'seed-{args.seed}', config[config_key]['code_dir'])
    test_dir = os.path.join(config['result_dir'], f'seed-{args.seed}', config[config_key]['test_dir'])
    submit_eval_file = os.path.join(result_dir, f'pass@{args.k}_{args.selection_strategy}{"SGT" if use_surrogate_ground_truth else ""}.jsonl')
    create_or_clear_file(submit_eval_file)

    rounds = config[config_key]['max_code_gens']
    evaluations = []
    for r in range(rounds):
        passed_count = 0
        total_count = 0
        prompt_tokens = 0
        completion_tokens = 0
        delta_sim_soft_per_task: List[Optional[float]] = []
        delta_sim_hard_per_task: List[Optional[float]] = []
        delta_pass_soft_per_task: List[float] = []
        delta_pass_hard_per_task: List[float] = []
        for i in tqdm(dataset.data_range):
            exec_file = os.path.join(result_dir, f'result_{i}.jsonl')
            code_file = os.path.join(code_dir, f'result_{i}.jsonl')
            test_file = os.path.join(test_dir, f'result_{i}.jsonl')
            assert os.path.exists(exec_file), f"exec_file {exec_file} does not exist, indicating some entries of the dataset were not considered"
            execs = read_jsonl(exec_file)
            codes = read_jsonl(code_file)
            tests = read_jsonl(test_file)
            selected_codes = get_k_codes(execs, r, selection_strategy, k, i)
            prompt_token_delta, completion_token_delta = get_token_counts(codes, tests, r)
            if code_file == test_file: # corrects for duplicate counting because codes and tests are generated together in a single file
                prompt_token_delta /= 2
                completion_token_delta /= 2
            for code in selected_codes:
                if use_surrogate_ground_truth:
                    test_result = [res for res in execs if res['r_tests'] == code['r_code'] and res['r_code'] == code['r_code']][0] 
                else:
                    assert any(res['r_tests'] == -1 and res['r_code'] == code['r_code'] for res in execs), f"no groundtruth for dataset entry {i} and code {code['r_code']}"
                    test_result = [res for res in execs if res['r_tests'] == -1 and res['r_code'] == code['r_code']][0] 
                if test_result['evaluation']['score'] == 1.0: # all tests passed
                    passed_count += 1
                    break
            total_count += 1
            prompt_tokens += prompt_token_delta
            completion_tokens += completion_token_delta

            # Estimate irreducible regret Delta for this task at round r
            if estimate_delta:
                window_rounds = list(range(max(0, r - estimate_delta_window_size + 1), r + 1))
                delta_result = estimate_irreducible_regret(execs, window_rounds)
                delta_sim_soft_per_task.append(delta_result['delta_sim_soft'])
                delta_sim_hard_per_task.append(delta_result['delta_sim_hard'])
                delta_pass_soft_per_task.append(delta_result['delta_pass_soft'])
                delta_pass_hard_per_task.append(delta_result['delta_pass_hard'])

        record = {
            'round': r,
            'pass_rate': passed_count / total_count,
            'passed_count': passed_count,
            'total_count': total_count,
            'prompt_tokens': prompt_tokens,
            'completion_tokens': completion_tokens,
            'total_tokens': prompt_tokens + completion_tokens
        }

        # Add per-task and dataset-level Delta estimates to the round record
        if estimate_delta:
            assert len(delta_sim_soft_per_task) == total_count, f"Mismatch: {len(delta_sim_soft_per_task)} delta_sim_soft values for {total_count} tasks"
            assert len(delta_sim_hard_per_task) == total_count, f"Mismatch: {len(delta_sim_hard_per_task)} delta_sim_hard values for {total_count} tasks"
            assert len(delta_pass_soft_per_task) == total_count, f"Mismatch: {len(delta_pass_soft_per_task)} delta_pass_soft values for {total_count} tasks"
            assert len(delta_pass_hard_per_task) == total_count, f"Mismatch: {len(delta_pass_hard_per_task)} delta_pass_hard values for {total_count} tasks"
            actual_window = min(estimate_delta_window_size, r + 1)
            if actual_window < 2:
                record['delta_sim_soft_mean'] = None
                record['delta_sim_hard_mean'] = None
                record['delta_pass_soft_mean'] = None
                record['delta_pass_hard_mean'] = None
            else:
                assert all(v is not None for v in delta_sim_soft_per_task), f"Round {r}: missing delta_sim_soft for some tasks"
                assert all(v is not None for v in delta_sim_hard_per_task), f"Round {r}: missing delta_sim_hard for some tasks"
                record['delta_sim_soft_mean'] = sum(delta_sim_soft_per_task) / total_count
                record['delta_sim_hard_mean'] = sum(delta_sim_hard_per_task) / total_count
                record['delta_pass_soft_mean'] = sum(delta_pass_soft_per_task) / total_count
                record['delta_pass_hard_mean'] = sum(delta_pass_hard_per_task) / total_count
            record['estimate_delta_window_size'] = actual_window
            record['delta_sim_soft_per_task'] = delta_sim_soft_per_task
            record['delta_sim_hard_per_task'] = delta_sim_hard_per_task
            record['delta_pass_soft_per_task'] = delta_pass_soft_per_task
            record['delta_pass_hard_per_task'] = delta_pass_hard_per_task

        evaluations.append(record)

    for r, eval in enumerate(evaluations):
        delta_str = ''
        if estimate_delta and eval.get('delta_sim_soft_mean') is not None:
            delta_str = (
                f", delta_sim_soft={round(eval['delta_sim_soft_mean'] * 100, 3)}%, delta_sim_hard={round(eval['delta_sim_hard_mean'] * 100, 3)}%"
                f", delta_pass_soft={round(eval['delta_pass_soft_mean'] * 100, 3)}%, delta_pass_hard={round(eval['delta_pass_hard_mean'] * 100, 3)}%"
                f" (w={eval['estimate_delta_window_size']})"
            )
        print(f"round {r}: pass@{k} is {str(round(eval['pass_rate'] * 100, 5))} ({eval['passed_count']}/{eval['total_count']}) with {round(eval['total_tokens'], 5)} tokens{delta_str}")
    write_jsonl(submit_eval_file, evaluations)
    print(json.dumps(evaluations, indent=4), flush=True)
    print('>>> save to ', submit_eval_file)