import os, subprocess
from typing import List, Set, Union, Dict
from utils import read_json, write_json
import signal, tempfile

MAX_OUTPUT_LEN = 10_000 # at most 10'000 characters
MEM_LIMIT_KB = 128 * 1024 * 1024 # 128 GB
MAX_USER_PROCESSES = 1_000 # 1000 processes
FILE_SIZE_LIMIT= 10 * 1024 * 1024 # 10 GB

# Helper function to unpack arguments for imap
def execute_wrapper(args):
    return execute(*args)

def execute(environment: str, id: int, run_dir: str, file_name: str, time_limit: int) -> None:
    """
    Executes a pytest suite.

    This function runs pytest on a specified Python test file within a given
    directory, using a timeout constraint. It captures the test execution result,
    reads the JSON report generated by pytest, and returns a structured result
    dictionary for further processing.

    Args:
        environment (str): Micromamba environment to activate for the given dataset.
        id (int): Unique identifier for this execution instance.
        run_dir (str): Directory path where the test file is located.
        file_name (str): Name of the test file to be executed.
        time_limit (int): Maximum time in seconds allowed for the test execution.

    Returns:
       None, but stores a dictionary at run_dir/return_{id}.json with entries
        'id' (int): the unique identifier for this execution instance
        'passed' (bool): whether all unit tests have been passed
        'total_i' (int): the total number of unit tests
        'passed_i' (int): the number of passed unit tests
        'output' (str): the standard output and standard error from the unit test

    Example:
        >>> execute('/path/to/env', 1, '/path/to/tests', 'test_example.py', 30)
    """
    assert isinstance(time_limit, int), f'the type of time_limit is {type(time_limit)}'
    report_name = f'report_{id}.json'
    return_name = f'return_{id}.json'
    report_path = os.path.join(run_dir, report_name)
    return_path = os.path.join(run_dir, return_name)
    env = os.environ.copy()
    env["PATH"] = f"{environment}/bin:{env['PATH']}"
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["HOME"] = "/tmp"
    env["NUMBA_CACHE_DIR"] = "/tmp"
    env["MPLCONFIGDIR"] = "/tmp"
    env["XDG_CACHE_HOME"] = "/tmp"
    env["OMP_NUM_THREADS"] = "1"
    env["OPENBLAS_NUM_THREADS"] = "1"
    env["MKL_NUM_THREADS"] = "1"
    env["NUMBA_NUM_THREADS"] = "1"
    env["TF_NUM_INTEROP_THREADS"] = "1"
    env["TF_NUM_INTRAOP_THREADS"] = "1"
    env["CUDA_VISIBLE_DEVICES"] = "-1"
    env["KERAS_BACKEND"] = "tensorflow"
    # Default values for failure
    passed = False
    passed_count = 0
    total_count = 0
    program_output = ""
    invalid = True
    process = None
    pgid = None # allows killing any spawned subprocesses
    with tempfile.TemporaryFile(mode='w+') as stdout_f, tempfile.TemporaryFile(mode='w+') as stderr_f:
        try:
            # --- CONSTRUCT THE SANDBOX ---
            # 1. Inner Command: ulimit + pytest
            inner_cmd = (
                f"ulimit -v {MEM_LIMIT_KB}; "
                f"ulimit -u {MAX_USER_PROCESSES}; "
                f"ulimit -f {FILE_SIZE_LIMIT}; "
                f"exec pytest --no-header --json-report --json-report-file={report_name} --timeout {time_limit} {file_name}"
            )
            # 2. Outer Command: Bubblewrap
            # --ro-bind / /      : Mount entire OS as Read-Only
            # --dev /dev         : Needed for /dev/null, random, etc.
            # --proc /proc       : Needed for process info
            # --bind run_dir ... : The ONLY place the code can write (Read-Write)
            # --tmpfs /tmp       : Give it a fake, empty /tmp (cleared on exit)
            # --share-net        : Keep network access (remove to block internet)
            # --die-with-parent  : Cleanup guarantee
            abs_run_dir = os.path.abspath(run_dir)
            bwrap_cmd = [
                'bwrap',
                '--ro-bind', '/', '/',
                '--dev', '/dev',
                '--proc', '/proc',
                '--bind', abs_run_dir, abs_run_dir, 
                '--tmpfs', '/tmp',
                '--perms', '1777', '--tmpfs', '/dev/shm',
                '--unshare-pid',
                '--unshare-ipc',
                '--share-net',
                '--die-with-parent',
                '--', 
                '/bin/bash', '-c', inner_cmd
            ]
            process = subprocess.Popen(
                bwrap_cmd,
                stdout=stdout_f, stderr=stderr_f,
                text=True, cwd=run_dir, env=env,
                start_new_session=True
            )
            pgid = os.getpgid(process.pid)
            process.wait(timeout=2*time_limit) # hard timeout limit
            stdout_f.seek(0)
            stderr_f.seek(0)
            # Read only up to MAX_OUTPUT_LEN to protect your RAM
            stdout_str = stdout_f.read(MAX_OUTPUT_LEN)
            stderr_str = stderr_f.read(MAX_OUTPUT_LEN)
            # Warn if truncated
            if len(stdout_str) >= MAX_OUTPUT_LEN:
                stdout_str += "\n... [Output Truncated]"
            if len(stderr_str) >= MAX_OUTPUT_LEN:
                stderr_str += "\n... [Output Truncated]"
            program_output = stdout_str + "\n" + stderr_str
            passed = process.returncode == 0
            if os.path.exists(report_path):
                file_size_mb = os.path.getsize(report_path) / (1024 * 1024)
                if file_size_mb <= 100: # 100 MB is max file size for report
                    try:
                        report = read_json(report_path)
                        passed_count = report['summary'].get('passed', 0)
                        total_count = report['summary']['total']
                        invalid = False
                    except Exception:
                        # File exists but is corrupted (e.g., process killed mid-write)
                        program_output += "\n[System]: JSON Report existed but was corrupted."
                        print("\n[System]: JSON Report existed but was corrupted.", flush=True)
                else:
                    program_output += f"\n[System]: JSON Report too large ({file_size_mb:.2f} MB). Potentially infinite print/log loop."
                    print(f"\n[System]: JSON Report too large ({file_size_mb:.2f} MB). Potentially infinite print/log loop.", flush=True)
            else:
                # File missing (e.g., pytest crashed hard or directory deleted)
                program_output += "\n[System]: No JSON report generated."
                print("\n[System]: No JSON report generated.", flush=True)
        except subprocess.TimeoutExpired as e:
            program_output += f"\n[System]: Hard Timeout ({2*time_limit}s) expired."
            print(f"\n[System]: Hard Timeout ({2*time_limit}s) expired.", flush=True)
        except Exception as e:
            # Handles missing directory (FileNotFoundError) or other OS issues
            program_output += f"\n[System]: Execution failed with error: {str(e)}"
            print(f"\n[System]: Execution failed with error: {str(e)}", flush=True)
        finally:
            if pgid is not None:
                try:
                    os.killpg(pgid, signal.SIGKILL)
                except: # is usually triggered since pgid will not exist
                    pass # The group is already gone
    write_json(return_path,
    {
        'id': id,
        'passed': passed,
        'total_i': total_count,
        'passed_i': passed_count,
        'invalid': invalid,
        'output': program_output,
    })
    

def coverage(environment: str, id: int, run_dir: str, file_name: str, time_limit: int) -> Dict:
    """
    Executes a pytest suite and reports test coverage.

    This function runs pytest on a specified Python module within a given
    directory, using a timeout constraint. It captures the line coverage,
    and returns a structured result dictionary for further processing.
    `file_name` specifies the code file whose line coverage should be computed. Assumes that unit
    tests are inside the same directory, and automatically discovers them based on pytests internal functionality.

    Args:
        environment (str): Micromamba environment to activate for the given dataset.
        id (int): Unique identifier for this execution instance.
        run_dir (str): Directory path where the test file is located.
        file_name (str): Name of the code file whose line coverage should be computed.
        time_limit (int): Maximum time in seconds allowed for the test execution.

    Returns:
       The result is a dictionary with entries
        'id' (int): the unique identifier for this execution instance
        'missing_lines' (list): line coverage information

    Example:
        >>> coverage('/path/to/env', 1, '/path/to/tests', 'test_example.py', 30)
    """
    assert isinstance(time_limit, int), f'the type of time_limit is {type(time_limit)}'
    coverage_path = os.path.join(run_dir, 'coverage.json')
    env = os.environ.copy()
    env["PATH"] = f"{environment}/bin:{env['PATH']}"
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["HOME"] = "/tmp"
    env["NUMBA_CACHE_DIR"] = "/tmp"
    env["MPLCONFIGDIR"] = "/tmp"
    env["XDG_CACHE_HOME"] = "/tmp"
    env["OMP_NUM_THREADS"] = "1"
    env["OPENBLAS_NUM_THREADS"] = "1"
    env["MKL_NUM_THREADS"] = "1"
    env["NUMBA_NUM_THREADS"] = "1"
    env["TF_NUM_INTEROP_THREADS"] = "1"
    env["TF_NUM_INTRAOP_THREADS"] = "1"
    env["CUDA_VISIBLE_DEVICES"] = "-1"
    env["KERAS_BACKEND"] = "tensorflow"
    process = None
    pgid = None
    try:
        # --- CONSTRUCT THE SANDBOX ---
        # 1. Inner Command: ulimit + pytest
        inner_cmd = (
            f"ulimit -v {MEM_LIMIT_KB}; "
            f"ulimit -u {MAX_USER_PROCESSES}; "
            f"ulimit -f {FILE_SIZE_LIMIT}; "
            f"exec pytest --cov={file_name[: -3]} --cov-report=json:coverage.json --timeout {time_limit}"
        )
        # 2. Outer Command: Bubblewrap
        # --ro-bind / /      : Mount entire OS as Read-Only
        # --dev /dev         : Needed for /dev/null, random, etc.
        # --proc /proc       : Needed for process info
        # --bind run_dir ... : The ONLY place the code can write (Read-Write)
        # --tmpfs /tmp       : Give it a fake, empty /tmp (cleared on exit)
        # --share-net        : Keep network access (remove to block internet)
        # --die-with-parent  : Cleanup guarantee
        abs_run_dir = os.path.abspath(run_dir)
        bwrap_cmd = [
            'bwrap',
            '--ro-bind', '/', '/',
            '--dev', '/dev',
            '--proc', '/proc',
            '--bind', abs_run_dir, abs_run_dir, 
            '--tmpfs', '/tmp',
            '--perms', '1777', '--tmpfs', '/dev/shm',
            '--unshare-pid',
            '--unshare-ipc',
            '--share-net',
            '--die-with-parent',
            '--', 
            '/bin/bash', '-c', inner_cmd
        ]
        process = subprocess.Popen(
            bwrap_cmd,
            stdout=subprocess.DEVNULL, # Discard output safely
            stderr=subprocess.DEVNULL, # Discard error safely
            text=True, cwd=run_dir, env=env,
            start_new_session=True
        )
        pgid = os.getpgid(process.pid)
        process.wait(timeout=2*time_limit) # hard timeout limit if soft limit fails
        if not os.path.exists(coverage_path):
            raise Exception
        report = read_json(coverage_path)
        missing_lines = report['files'][file_name]['missing_lines']
        covered_lines = report['files'][file_name]['executed_lines']
    except:
        missing_lines = None
        covered_lines = None
    finally:
        if pgid:
            try:
                os.killpg(pgid, signal.SIGKILL)
            except: # is usually triggered since pgid will not exist
                pass # The group of processes is already gone
        return {
            'id': id,
            'missing_lines': missing_lines,
            'covered_lines': covered_lines
        }

def add_cov_message(
        code: str,
        lines_covered: Union[List, Set],
        lines_not_covered: Union[List, Set],
        add_block_delimiters:bool = True,
        covered_c: str = '+',
        not_covered_c: str = '-',
        non_executable_c: str = ' ',
) -> str:
    """
    Adds coverage indicators to each line of code based on whether the line is covered or not.

    This function takes a code string and a collection of line numbers that are not covered,
    then prepends coverage indicators to each line. Covered lines are prefixed with
    'covered_c' (default '+'), while uncovered lines are prefixed with 'not_covered_c' (default '-').
    If a line is non-executable (e.g. a comment), an empty prefix is used.

    Args:
        code (str): The source code as a string, with lines separated by newlines.
        lines_covered (Union[List, Set]): A list or set of line numbers (0-indexed) that are covered by tests.
        lines_not_covered (Union[List, Set]): A list or set of line numbers (0-indexed) that are not covered by tests.
        add_block_delimiters (bool, optional): Whether to add block delimiters (```) around annotated code. Defaults to True.
        covered_c (str, optional): Character to prefix covered lines. Defaults to '+'.
        not_covered_c (str, optional): Character to prefix uncovered lines. Defaults to '-'.
        non_executable_c (str, optional): Character to prefix inexecutable lines. Defaults to '+'.

    Returns:
        str: The code with coverage indicators added to each line, with trailing newlines removed.

    Example:
        >>> code = "def hello():\\n    print('Hello')\\n    return True"
        >>> add_cov_message(code, [0, 2], [1])
        "[+] def hello():\\n[-]     print('Hello')\\n[+]     return True"
    """
    res = 'Line Coverage Report: [+] indicates covered lines, [-] indicates uncovered lines.\n'
    if add_block_delimiters:
        res += '```\n'
    lines = code.split('\n')
    for i, line in enumerate(lines):
        if i in lines_not_covered:
            res += f'[{not_covered_c}] ' + line + '\n'
        elif i in lines_covered:
            res += f'[{covered_c}] ' + line + '\n'
        else:
            res += f' {non_executable_c} ' + line + '\n'
    if add_block_delimiters:
        res += '```'
    return res.rstrip()